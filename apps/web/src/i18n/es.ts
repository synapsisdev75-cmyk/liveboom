export type MessageTree = typeof es;

type DeepString<T> = T extends string
  ? string
  : { [K in keyof T]: DeepString<T[K]> };

export type Catalog = DeepString<MessageTree>;

export type MessageKey = {
  [K in keyof MessageTree]: MessageTree[K] extends string
    ? K & string
    : MessageTree[K] extends Record<string, unknown>
      ? {
          [P in keyof MessageTree[K]]: `${K & string}.${P & string}`;
        }[keyof MessageTree[K]]
      : never;
}[keyof MessageTree];
